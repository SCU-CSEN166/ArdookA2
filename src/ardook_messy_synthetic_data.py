"""Ardook messy synthetic data: the extra synthetic data with the noise real trackers have.

Same tables, columns and loaders as src.ardook_extra_synthetic_data, so Pipeline treats both identically.
Grants are generated by the same seeded rules, then roughened: blank cells, typos, inconsistent casing
and separators, mixed deadline and amount formats, vague requirements, near-duplicate listings, and
profiles that are short, misspelled or missing attributes. Nothing is sourced from a model or the web.

Labels stay honest about what the text supports. A requirement clause dropped from a grant is also
dropped from its rules, and labels are computed from the attributes a profile actually exposes.
Where the data cannot support a confident call, the label is "needs_review" and the reason is stored:
`review_flags` lists why a grant row cannot be fully trusted, and `matches.reason` says why a
profile/grant pair needs a human instead of being called a match.

Run `python -m src.ardook_messy_synthetic_data` to rebuild data/ardook_messy_synthetic_data.db.
Output is seeded, so reruns are identical.
"""

import json
import random
import sqlite3
from contextlib import closing
from datetime import timedelta
from pathlib import Path

import pandas as pd

from src.ardook_extra_synthetic_data import (
    FOCUS,
    REFERENCE_DATE,
    _eligible,
    _grant,
    _profile,
    NAME_A,
    NAME_B,
    NAME_C,
    load_checker as _load_checker,
    load_grants as _load_grants,
    load_matches as _load_matches,
    load_profiles as _load_profiles,
)
from src.ingest import COLUMNS
from src.paths import REPO_ROOT

DB_PATH = REPO_ROOT / "data/ardook_messy_synthetic_data.db"

VAGUE_CLAUSES = [
    "see website for full criteria",
    "additional conditions may apply",
    "eligibility reviewed case by case",
    "details to be confirmed with program officer",
]
VAGUE_FOCUS = ["Supports community impact", "Supports social good", "Supports innovation"]
VAGUE_PROFILES = [
    "We help people in our community.",
    "small org doing good work",
    "Our mission is to make things better.",
    "nonprofit - see our website",
]


def _typo(text: str, rng: random.Random) -> str:
    """Swap two adjacent letters inside one longer word."""
    words = text.split(" ")
    candidates = [i for i, w in enumerate(words) if len(w) > 4 and w.isalpha()]
    if not candidates:
        return text
    i = rng.choice(candidates)
    j = rng.randrange(1, len(words[i]) - 2)
    w = words[i]
    words[i] = w[:j] + w[j + 1] + w[j] + w[j + 2:]
    return " ".join(words)


def _spacing(text: str, rng: random.Random) -> str:
    return rng.choice([f"  {text}", f"{text}  ", text.replace(" ", "  ", 1), f"{text}\n", f"\t{text}"])


def _casing(text: str, rng: random.Random) -> str:
    return rng.choice([text.upper(), text.lower(), text.title()])


def _key(name: str) -> str:
    """Program name as clean_grants stores it (whitespace collapsed); rules must be keyed on this."""
    return " ".join(name.split())


def _name_variant(name: str, rng: random.Random) -> str:
    return rng.choice(
        [name.upper(), name.lower(), f"{name} (2026)", f"{name} - rolling", name.replace(" ", "  ", 1), _typo(name, rng)]
    )


def _messy_deadline(deadline: str, rng: random.Random) -> str:
    if len(deadline) == 10 and deadline[4] == "-":
        year, month, day = deadline.split("-")
        return rng.choice(
            [
                f"{day}/{month}/{year}",
                f"{int(month)}/{int(day)}/{year[2:]}",
                f"{pd.Timestamp(deadline):%b} {int(day)}, {year}",
                f"end of {pd.Timestamp(deadline):%B}",
                "TBD",
                "",
            ]
        )
    return deadline


def _messy_amount(amount: str, rng: random.Random) -> str:
    return rng.choice(["varies", "TBD", "", f"~{amount}", amount.replace(",", ""), amount.lower(), f"{amount} (approx.)"])


def _roughen(row: dict, rules: list[dict], rng: random.Random) -> tuple[dict, list[dict], list[tuple[str, str]]]:
    """Apply noise to one clean grant row. Returns the row, the rules its text still supports, and
    (field, reason) flags for everything a human must check because the text no longer settles it."""
    row, rules = dict(row), list(rules)
    flags: list[tuple[str, str]] = []

    if rng.random() < 0.15:
        row["Program"] = _name_variant(row["Program"], rng)
    for rule in rules:
        rule["program"] = _key(row["Program"])

    # Requirements: rule clauses may vanish (and their rules with them); other clauses get noisy.
    evidence = {r["evidence"] for r in rules}
    kept = []
    for clause in row["Core Requirements"].split("; "):
        if clause in evidence:
            if rng.random() < 0.08:
                rules = [r for r in rules if r["evidence"] != clause]
                flags.append(("requirements", "a requirement was removed from the text, so eligibility cannot be fully checked"))
                continue
            kept.append(clause)
        elif clause.startswith("Supports ") and rng.random() < 0.10:
            kept.append(rng.choice(VAGUE_FOCUS))
            flags.append(("requirements", "program scope is vague, so fit cannot be judged from the text"))
        elif rng.random() < 0.20:
            kept.append(_typo(clause, rng))
        elif rng.random() < 0.15:
            continue
        else:
            kept.append(clause)
    if rng.random() < 0.15:
        kept.insert(rng.randrange(len(kept) + 1), rng.choice(VAGUE_CLAUSES))
        flags.append(("requirements", "requirements point elsewhere or are open-ended"))
    row["Core Requirements"] = rng.choice(["; ", ", ", " | ", ";\n", ". "]).join(kept) if kept else ""
    if not kept:
        flags.append(("requirements", "requirements are blank"))

    if rng.random() < 0.15:
        row["Type"] = _casing(row["Type"], rng)
    if rng.random() < 0.10:
        row["Type"] = ""
    if rng.random() < 0.15:
        row["Amount / Benefit"] = _messy_amount(row["Amount / Benefit"], rng)
        if row["Amount / Benefit"] in ("", "varies", "TBD"):
            flags.append(("amount", "amount is missing or not stated"))
    if rng.random() < 0.20:
        row["Deadline"] = _messy_deadline(row["Deadline"], rng)
        if row["Deadline"] in ("", "TBD") or row["Deadline"].startswith("end of"):
            flags.append(("deadline", "deadline is missing or not an exact date"))
        elif row["Deadline"][:1].isdigit() and row["Deadline"][2:3] == "/":
            flags.append(("deadline", "deadline is written in an ambiguous date format"))
    if rng.random() < 0.10:
        row["Current Status (as last reported)"] = rng.choice(["", row["Current Status (as last reported)"].lower()])
    if rng.random() < 0.20:
        row["Fit"] = rng.choice(["", "?", row["Fit"].lower(), "Good", row["Fit"].upper()])
    if rng.random() < 0.20:
        row["Why It Fits Ardook Data"] = ""
    if rng.random() < 0.25:
        row["Key Concern / Disqualifier"] = ""
    elif rng.random() < 0.10 and kept:
        row["Key Concern / Disqualifier"] = f"Note: {kept[0]}"
    if rng.random() < 0.10:
        row["Recommended Action"] = ""
    roll = rng.random()
    if roll < 0.15:
        row["Official Source"] = ""
        flags.append(("official_source", "no official source to quote"))
    elif roll < 0.25:
        row["Official Source"] = "TBD"
        flags.append(("official_source", "no official source to quote"))
    elif roll < 0.35:
        row["Official Source"] = row["Official Source"].replace("https://", "http://") + "/"
    row["Applied?"] = rng.choice([row["Applied?"], row["Applied?"], row["Applied?"], row["Applied?"].lower(), "N", ""]) if rng.random() < 0.10 else row["Applied?"]

    for column in ("Program", "Type", "Why It Fits Ardook Data", "Key Concern / Disqualifier"):
        if row[column] and rng.random() < 0.08:
            row[column] = _spacing(row[column], rng)
    return row, rules, flags


def _messy_profile(profile: tuple, rng: random.Random) -> tuple:
    number, description, attributes, focus = profile
    attributes = json.loads(attributes)
    for key in list(attributes):  # on top of the clean data's 10%: intake forms are often half empty
        if rng.random() < 0.20:
            del attributes[key]
    roll = rng.random()
    if roll < 0.12:
        description = rng.choice(VAGUE_PROFILES)
    elif roll < 0.35:
        description = _typo(description, rng)
    elif roll < 0.50:
        description = description.lower().rstrip(".")
    elif roll < 0.60:
        description = f"{description} Founded in 2014. Board meets monthly. Contact us for volunteer opportunities."
    return number, description, json.dumps(attributes), focus


def build(path: Path = DB_PATH, seed: int = 2166, n_grants: int = 120, n_duplicates: int = 15, n_profiles: int = 200):
    rng = random.Random(seed)
    names = [f"{a} {b} {c}" for a in NAME_A for b in NAME_B for c in NAME_C]
    names = rng.sample(names, n_grants)

    grants, rules = [], []
    for name in names:
        clean_row, clean_rules = _grant(rng, name)
        rules_for_row = [{"program": name, **r} for r in clean_rules]
        grants.append((clean_row, rules_for_row))
    grants.sort(key=lambda g: (g[0]["Deadline"][:1] not in "2", g[0]["Deadline"]))  # dated rows first, like the tracker

    rows, row_rules, row_flags = [], [], []
    for clean_row, clean_rules in grants:
        row, kept_rules, flags = _roughen(clean_row, clean_rules, rng)
        rows.append(row)
        row_rules.append(kept_rules)
        row_flags.append(flags)

    # Near-duplicate listings: the same program re-listed under a variant name with a different status.
    source = list(zip(rows, row_rules, row_flags))
    if not 0 <= n_duplicates <= len(source):
        raise ValueError("n_duplicates must be between 0 and n_grants")
    used = {_key(row["Program"]) for row in rows}
    for original, original_rules, original_flags in rng.sample(source, n_duplicates):
        copy = dict(original)
        for _ in range(50):  # the cleaned name must differ, or rules would be keyed twice
            copy["Program"] = _name_variant(original["Program"], rng)
            if _key(copy["Program"]) not in used:
                break
        else:
            continue
        used.add(_key(copy["Program"]))
        copy["Current Status (as last reported)"] = rng.choice(["Open as last reported", "Closed", "Watchlist", ""])
        copy_rules = [{**r, "program": _key(copy["Program"])} for r in original_rules]
        copy_flags = original_flags + [("program", f"possible duplicate listing of '{original['Program']}'")]
        position = rng.randrange(len(rows) + 1)
        rows.insert(position, copy)
        row_rules.insert(position, copy_rules)
        row_flags.insert(position, copy_flags)

    for order, row in enumerate(rows, start=1):  # priority order with gaps, repeats and blanks
        row["Priority / Deadline Order"] = rng.choice([order, order, order, order, order + 1, max(order - 1, 1), None])

    rules_by_program: dict[str, list[dict]] = {}
    for row, rule_list in zip(rows, row_rules):
        rules_by_program.setdefault(_key(row["Program"]), []).extend(rule_list)
    rule_records = [
        {"program": r["program"], "attribute": r["attribute"], "operator": r["operator"],
         "value": json.dumps(r["value"]), "evidence": r["evidence"]}
        for rule_list in row_rules for r in rule_list
    ]
    flag_records = [
        (index + 2, field, reason)  # source_row, as clean_grants numbers it
        for index, flags in enumerate(row_flags) for field, reason in dict.fromkeys(flags)
    ]

    profiles, matches = [], []
    for number in range(1, n_profiles + 1):
        profile, focus = _profile(rng, number)
        profile = _messy_profile(profile, rng)
        profiles.append(profile)
        attributes = json.loads(profile[2])
        for index, row in enumerate(rows):
            program_rules = rules_by_program.get(_key(row["Program"]), [])
            reason = ""
            if focus not in json.loads(row["Focus"]):
                label = "unrelated"
            elif not _eligible(attributes, program_rules):
                label = "ineligible"
            else:
                # Eligible only on what is known. Anything unverifiable goes to a human, never to "match".
                missing = sorted({r["attribute"] for r in program_rules if r["attribute"] not in attributes})
                reasons = [f"profile is missing {', '.join(missing)}"] if missing else []
                reasons += sorted({why for field, why in row_flags[index] if field in ("requirements", "program")})
                label, reason = ("needs_review", "; ".join(reasons)) if reasons else ("match", "")
            matches.append((number, index + 2, label, reason))  # source_row, as clean_grants numbers it

    path.parent.mkdir(parents=True, exist_ok=True)
    path.unlink(missing_ok=True)
    with closing(sqlite3.connect(path)) as db:
        pd.DataFrame(rows, columns=list(COLUMNS) + ["Focus"]).to_sql("grants", db, index=False)
        pd.DataFrame(rule_records, columns=["program", "attribute", "operator", "value", "evidence"]).to_sql("rules", db, index=False)
        db.execute("CREATE TABLE profiles (id, description, attributes, focus)")
        db.executemany("INSERT INTO profiles VALUES (?, ?, ?, ?)", profiles)
        db.execute("CREATE TABLE matches (profile_id, source_row, label, reason)")
        db.executemany("INSERT INTO matches VALUES (?, ?, ?, ?)", matches)
        db.execute("CREATE TABLE review_flags (source_row, field, reason)")
        db.executemany("INSERT INTO review_flags VALUES (?, ?, ?)", flag_records)
        db.commit()


def load_grants(path: Path = DB_PATH) -> pd.DataFrame:
    return _load_grants(path)


def load_checker(path: Path = DB_PATH):
    return _load_checker(path)


def load_profiles(path: Path = DB_PATH) -> pd.DataFrame:
    return _load_profiles(path)


def load_matches(path: Path = DB_PATH) -> pd.DataFrame:
    return _load_matches(path)


def load_review_flags(path: Path = DB_PATH) -> pd.DataFrame:
    with closing(sqlite3.connect(path)) as db:
        return pd.read_sql("SELECT * FROM review_flags", db)


if __name__ == "__main__":
    build()
    print(f"Wrote {DB_PATH}")
